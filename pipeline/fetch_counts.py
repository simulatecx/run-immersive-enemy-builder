"""Bake the public crowd rollups into RUN/data/generated/crowd_counts.lua.

Reads the `rareKillCounts` rollups over the Firestore REST API with a gcloud OAuth
token (the rules allow public reads, but App Check is enforced project-wide, so an
unauthenticated read is 403 - server-to-server OAuth bypasses it, the same method
Foresight's pipeline/fetch_baselines.py uses; raw rareKills stay write-only). Run
`gcloud auth login` once. Emits the empty-safe Lua table the notoriety blend reads:
RUN.gen.crowdCounts[npc] = { total = n, wipes = n }.

NEVER blocks the gate: on ANY failure (offline, no gcloud token, 403, quota, junk
data) an existing bake is left alone - or the empty table is written when none
exists - and the exit code stays 0. Run it before packaging
a release zip so fresh counts ride along. Suppressed buckets ({ low: true })
and encounter-keyed wipe docs are skipped: the in-game blend only ever sees
published per-npc totals.

Usage: python pipeline/fetch_counts.py
"""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).parent.parent
OUT_PATH = ROOT / "RUN" / "data" / "generated" / "crowd_counts.lua"

PROJECT = "wow-foresight"
BASE = (f"https://firestore.googleapis.com/v1/projects/{PROJECT}"
        "/databases/(default)/documents/rareKillCounts")
PAGE_SIZE = 300
TIMEOUT = 20

HEADER = (
    "-- GENERATED by pipeline/fetch_counts.py from the public rareKillCounts rollups"
    " - DO NOT EDIT.\n"
    "-- Server-verified crowd counts (pre-suppressed: only buckets at/above MIN_BUCKET"
    " publish totals).\n"
    "-- Empty-safe: model/notoriety.lua blends these as the third source and reads 0"
    " when absent.\n"
    "local _, RUN = ...\n"
    "if not RUN then RUN = _G.RunAdvisor or {}; _G.RunAdvisor = RUN end\n"
    "RUN.gen = RUN.gen or {}\n"
    "RUN.gen.crowdCounts = {\n"
)
FOOTER = "}\nreturn RUN.gen.crowdCounts\n"


def _access_token() -> str:
    # App Check is enforced project-wide, so an unauthenticated REST read is 403 even
    # though the rules allow public reads (Foresight's own `aggregates` is 403 the same
    # way). Server-to-server gcloud OAuth bypasses App Check - the same method Foresight's
    # pipeline/fetch_baselines.py uses. Resolve the full path so Windows finds gcloud.cmd.
    exe = shutil.which("gcloud") or "gcloud"
    res = subprocess.run([exe, "auth", "print-access-token"],
                         capture_output=True, text=True, timeout=30)
    if res.returncode != 0 or not res.stdout.strip():
        raise RuntimeError("gcloud token unavailable (run `gcloud auth login`): "
                           + (res.stderr or "").strip())
    return res.stdout.strip()


def _num(fields: dict, key: str):
    v = fields.get(key)
    if not isinstance(v, dict):
        return None
    if "integerValue" in v:
        try:
            return int(v["integerValue"])
        except (TypeError, ValueError):
            return None
    if "doubleValue" in v:
        try:
            return int(float(v["doubleValue"]))
        except (TypeError, ValueError):
            return None
    return None


def fetch_counts() -> dict[int, dict]:
    """npc -> { total, wipes } from every published (non-suppressed) npc doc."""
    counts: dict[int, dict] = {}
    bearer = _access_token()
    token = None
    while True:
        qs = {"pageSize": str(PAGE_SIZE)}
        if token:
            qs["pageToken"] = token
        url = BASE + "?" + urllib.parse.urlencode(qs)
        req = urllib.request.Request(url, headers={"Authorization": f"Bearer {bearer}"})
        with urllib.request.urlopen(req, timeout=TIMEOUT) as resp:
            body = json.loads(resp.read().decode("utf-8"))
        for doc in body.get("documents", []):
            fields = doc.get("fields", {})
            if "booleanValue" in fields.get("low", {}) and fields["low"]["booleanValue"]:
                continue  # suppressed bucket: no total published yet
            npc = _num(fields, "npc")
            if npc is None or npc < 1:
                continue  # encounter-keyed wipe docs and junk are skipped
            total = _num(fields, "total") or 0
            wipes = _num(fields, "wipes") or 0
            if total > 0 or wipes > 0:
                counts[npc] = {"total": max(total, 0), "wipes": max(wipes, 0)}
        token = body.get("nextPageToken")
        if not token:
            break
    return counts


def emit(counts: dict[int, dict]) -> str:
    lines = [HEADER]
    for npc in sorted(counts):
        e = counts[npc]
        lines.append(f"    [{npc}] = {{ total = {e['total']}, wipes = {e['wipes']} }},\n")
    lines.append(FOOTER)
    return "".join(lines)


def main() -> int:
    try:
        counts = fetch_counts()
    except Exception as e:  # offline/403/quota/parse - never block the gate
        if OUT_PATH.exists():
            print(f"fetch_counts: fetch failed ({e}); keeping the existing bake")
        else:
            OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
            OUT_PATH.write_text(emit({}), encoding="utf-8")
            print(f"fetch_counts: fetch failed ({e}); wrote the empty-safe bake")
        return 0
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(emit(counts), encoding="utf-8")
    print(f"fetch_counts: baked {len(counts)} creature count(s) -> {OUT_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
