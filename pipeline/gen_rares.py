"""Generate RUN/data/generated/rares.lua from the Forever client's Creature DB2.

Fetches Creature.csv from wago.tools (cached per build), keeps rare /
rare-elite / world-boss species, and emits the names table the addon uses to
name heard-only creatures and flag known rares. OUR data from the client -
never another addon's database. Coordinates are not in Creature.db2; the
waypoint markKnown path stays dormant until a position source is added.

Usage: python gen_rares.py [--build 1.60.1.70338] [--force]
"""

from __future__ import annotations

import argparse
import csv
import sys
import urllib.request
from pathlib import Path

DEFAULT_BUILD = "1.60.1.70685"   # Forever LIVE launch build (verified 2026-11-03)
BASE_URL = "https://wago.tools/db2/Creature/csv?build={build}"
OUT = Path(__file__).parent.parent / "RUN" / "data" / "generated" / "rares.lua"

CLASSIFICATIONS = { "2": "rareelite", "3": "worldboss", "4": "rare" }


def fetch(build: str, force: bool) -> Path:
    cache = Path(__file__).parent / "cache" / build
    cache.mkdir(parents=True, exist_ok=True)
    dest = cache / "Creature.csv"
    if dest.exists() and not force:
        print(f"cached: {dest}")
        return dest
    url = BASE_URL.format(build=build)
    print(f"fetching {url}")
    req = urllib.request.Request(url, headers={"User-Agent": "RUN-addon-pipeline"})
    with urllib.request.urlopen(req, timeout=180) as resp:
        dest.write_bytes(resp.read())
    print(f"saved {dest} ({dest.stat().st_size // 1024} KB)")
    return dest


def lua_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def generate(build: str, force: bool) -> int:
    src = fetch(build, force)
    rares = []
    with src.open(encoding="utf-8", newline="") as fh:
        reader = csv.DictReader(fh)
        cols = reader.fieldnames or []
        id_col = "ID" if "ID" in cols else cols[0]
        name_col = "Name_lang" if "Name_lang" in cols else None
        cls_col = "Classification" if "Classification" in cols else None
        if not name_col or not cls_col:
            print(f"GEN RED: unexpected Creature.csv columns: {cols[:12]}")
            print("(a poisoned cache - e.g. an HTML error page - persists "
                  "until you re-run with --force)")
            return 1
        for row in reader:
            cls = CLASSIFICATIONS.get((row.get(cls_col) or "").strip())
            if not cls:
                continue
            name = (row.get(name_col) or "").strip()
            npc = (row.get(id_col) or "").strip()
            if name and npc.isdigit():
                rares.append((int(npc), name, cls))
    rares.sort()

    lines = [
        "-- GENERATED by pipeline/gen_rares.py from Forever Creature DB2 "
        f"(build {build}) - DO NOT EDIT.",
        "-- Curated corrections belong in data/overrides.lua (overrides win on merge).",
        "",
        "local _, RUN = ...",
        'if not RUN then RUN = _G.RunAdvisor or {}; _G.RunAdvisor = RUN end',
        "",
        "RUN.gen = RUN.gen or {}",
        "",
        "RUN.gen.rares = {",
    ]
    for npc, name, cls in rares:
        lines.append(f'    [{npc}] = {{ name = "{lua_escape(name)}", classification = "{cls}" }},')
    lines += ["}", "", "return RUN.gen.rares", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.name}: {len(rares)} rare/rare-elite/world-boss species (build {build})")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build", default=DEFAULT_BUILD)
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()
    return generate(args.build, args.force)


if __name__ == "__main__":
    sys.exit(main())
