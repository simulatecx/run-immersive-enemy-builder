"""Generate RUN's crowd-share allow-list mirrors from the ONE source of truth.

Usage:
    python gen_crowd_schema.py          # write all mirrors
    python gen_crowd_schema.py --check  # fail (exit 1) if any mirror has drifted

Source:  data/rare-kills-schema.json  (the allow-list: envelope + event shapes)
Mirrors:
  - RUN/data/generated/crowd_schema.lua         (addon: allow-lists + caps + forbidden)
  - firebase/rareKills.rules.partial            (validRareKill block, between markers)
  - ../marketing/web/run-crowd-schema.js        (web sanitize for run.html; emitted
    only when the sibling Foresight repo is checked out)

The check ALSO verifies (when the sibling repo is present) that the Foresight repo's
web/firestore.rules contains the exact generated validRareKill block between the same
markers - the parity law from docs/NOTES.md section 6: one schema file generates every
gate, and the ship gate fails on drift so a new field can never leak past one gate.
This script never WRITES the Foresight rules file (append-only ownership; the block is
applied there by hand once and then only verified).

Offline build tooling - never ships, never networks.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).parent.parent
SCHEMA_PATH = ROOT / "data" / "rare-kills-schema.json"
LUA_PATH = ROOT / "RUN" / "data" / "generated" / "crowd_schema.lua"
PARTIAL_PATH = ROOT / "firebase" / "rareKills.rules.partial"

def _resolve_marketing_root() -> Path:
    """The Foresight repo that carries the DEPLOYABLE shared surface.

    Candidates in order: the RUN_MARKETING_ROOT env var; the `overlay`
    sibling (the real Foresight repo at the standard dev location - wins
    once the RUN-surface branch merges to main); a `marketing` sibling;
    the orca worktree where the surface currently lives (branch
    simulatecx/marketing). First candidate whose web/ carries the RUN
    surface marker wins; else first with a web/ dir; else the first
    candidate (the check degrades gracefully when absent).
    """
    import os
    candidates = []
    env = os.environ.get("RUN_MARKETING_ROOT")
    if env:
        candidates.append(Path(env))
    candidates += [
        ROOT.parent / "overlay",
        ROOT.parent / "marketing",
        Path(r"C:\Users\BradsPC_2022\orca\workspaces\overlay\marketing"),
    ]
    for c in candidates:
        if (c / "web" / "run-crowd-schema.js").exists():
            return c
    for c in candidates:
        if (c / "web").is_dir():
            return c
    return candidates[0]


MARKETING_ROOT = _resolve_marketing_root()
JS_PATH = MARKETING_ROOT / "web" / "run-crowd-schema.js"
MARKETING_RULES_PATH = MARKETING_ROOT / "web" / "firestore.rules"

RULES_BEGIN = "// BEGIN generated validRareKill"
RULES_END = "// END generated validRareKill"

GEN_NOTE = "GENERATED by pipeline/gen_crowd_schema.py from data/rare-kills-schema.json - DO NOT EDIT."

EVENT_KINDS = ("const", "string", "number", "map")
FIELD_KINDS = ("const", "string", "number", "map", "bool", "list")


# ---- load -------------------------------------------------------------------

def load_schema() -> dict:
    schema = json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))
    forbidden = {k.lower() for k in schema["forbidden"]}
    fields = schema["fields"]
    keys = [f["key"] for f in fields]
    if len(keys) != len(set(keys)):
        raise ValueError("rare-kills-schema.json: duplicate envelope field key")
    for f in fields:
        if f["tier"] not in ("anon", "identifying"):
            raise ValueError(f"field {f['key']}: unknown tier {f['tier']!r}")
        if f["kind"] not in FIELD_KINDS:
            raise ValueError(f"field {f['key']}: unknown kind {f['kind']!r}")
        if f["key"].lower() in forbidden:
            raise ValueError(f"field {f['key']} is on the forbidden list")
    if any(f["tier"] == "identifying" for f in fields) and not any(f["key"] == "named" for f in fields):
        raise ValueError("identifying fields require a 'named' gate field")
    for kind, ev in schema["events"].items():
        ekeys = [f["key"] for f in ev["fields"]]
        if len(ekeys) != len(set(ekeys)):
            raise ValueError(f"event {kind}: duplicate field key")
        for f in ev["fields"]:
            if f["kind"] not in EVENT_KINDS:
                raise ValueError(f"event {kind}.{f['key']}: unknown kind {f['kind']!r}")
            if f["key"].lower() in forbidden:
                raise ValueError(f"event {kind}.{f['key']} is on the forbidden list")
            if "tier" in f:
                raise ValueError(f"event {kind}.{f['key']}: events are anon-only, no tiers")
        kf = next((f for f in ev["fields"] if f["key"] == "k"), None)
        if not kf or kf.get("kind") != "const" or kf.get("value") != kind:
            raise ValueError(f"event {kind}: needs k const field equal to its kind name")
    return schema


def allow_keys(fields: list[dict]) -> list[str]:
    return [f["key"] for f in fields]


def anon_keys(fields: list[dict]) -> list[str]:
    return [f["key"] for f in fields if f.get("tier", "anon") == "anon"]


def required_keys(fields: list[dict]) -> list[str]:
    return [f["key"] for f in fields if f.get("required")]


def caps(fields: list[dict]) -> dict:
    return {f["key"]: f["maxSize"] for f in fields if "maxSize" in f}


# ---- Lua mirror (addon) -----------------------------------------------------

def _lua_str(s: str) -> str:
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def _lua_list(items: list[str]) -> str:
    return "{ " + ", ".join(_lua_str(x) for x in items) + " }"


def _lua_caps(cap_items: dict) -> str:
    return "{ " + ", ".join(f"{k} = {int(v)}" for k, v in sorted(cap_items.items())) + " }"


def emit_lua(schema: dict) -> str:
    env = schema["fields"]
    lines = [
        f"-- {GEN_NOTE}",
        "-- The crowd-share allow-list, single-sourced. core/share.lua reads these so the",
        "-- payload builder's key set, forbidden list and caps can never drift from the",
        "-- web sanitize + Firestore rules (generated from the same JSON).",
        "local _, RUN = ...",
        "if not RUN then RUN = _G.RunAdvisor or {}; _G.RunAdvisor = RUN end",
        "RUN.gen = RUN.gen or {}",
        "RUN.gen.crowdSchema = {",
        f"    version = {int(schema['schemaVersion'])},",
        f"    site = {_lua_str(schema['site'])},",
        f"    maxEvents = {int(next(f['maxSize'] for f in env if f['key'] == 'events'))},",
        f"    kinds = {_lua_list(list(schema['events'].keys()))},",
        f"    allow = {_lua_list(allow_keys(env))},",
        f"    anonAllow = {_lua_list(anon_keys(env))},",
        f"    required = {_lua_list(required_keys(env))},",
        f"    forbidden = {_lua_list(schema['forbidden'])},",
        f"    caps = {_lua_caps(caps(env))},",
        "    events = {",
    ]
    for kind, ev in schema["events"].items():
        ef = ev["fields"]
        parts = [
            f"allow = {_lua_list(allow_keys(ef))}",
            f"required = {_lua_list(required_keys(ef))}",
        ]
        cap_items = caps(ef)
        if cap_items:
            parts.append(f"caps = {_lua_caps(cap_items)}")
        snap = next((f for f in ef if f["kind"] == "map" and "keys" in f), None)
        if snap:
            parts.append(f"{snap['key']}Allow = {_lua_list(snap['keys'])}")
        lines.append(f"        {kind} = {{ " + ", ".join(parts) + " },")
    lines += [
        "    },",
        "}",
        "return RUN.gen.crowdSchema",
    ]
    return "\n".join(lines) + "\n"


# ---- JS mirror (web sanitize for run.html) ----------------------------------

def _js(v) -> str:
    return json.dumps(v)


def _js_field(f: dict) -> str:
    parts = [f'key: {_js(f["key"])}']
    if "tier" in f:
        parts.append(f'tier: {_js(f["tier"])}')
    parts.append(f'kind: {_js(f["kind"])}')
    for opt in ("value", "min", "max", "maxSize", "matches", "of", "keys"):
        if opt in f:
            parts.append(f"{opt}: {_js(f[opt])}")
    parts.append(f'required: {_js(bool(f.get("required")))}')
    return "    { " + ", ".join(parts) + " },"


def emit_js(schema: dict) -> str:
    env = schema["fields"]
    lines = [
        f"// {GEN_NOTE}",
        "// Source of truth lives in the run-forever repo. web/run.html imports this so its",
        "// allow-list + banned keys match the RUN addon builder and the Firestore rules",
        "// exactly. Edit data/rare-kills-schema.json there and regenerate; never here.",
        "export const RUN_CROWD_SCHEMA = {",
        f"  version: {int(schema['schemaVersion'])},",
        f"  collection: {_js(schema['collection'])},",
        f"  site: {_js(schema['site'])},",
        f"  maxEvents: {int(next(f['maxSize'] for f in env if f['key'] == 'events'))},",
        f"  kinds: {_js(list(schema['events'].keys()))},",
        "  fields: [",
        *[_js_field(f) for f in env],
        "  ],",
        "  events: {",
    ]
    for kind, ev in schema["events"].items():
        lines.append(f"    {_js(kind)}: {{")
        lines.append("      fields: [")
        for f in ev["fields"]:
            lines.append("    " + _js_field(f))
        lines.append("      ],")
        lines.append(f"      allow: {_js(allow_keys(ev['fields']))},")
        lines.append(f"      required: {_js(required_keys(ev['fields']))},")
        lines.append("    },")
    lines += [
        "  },",
        f"  allow: {_js(allow_keys(env))},",
        f"  forbidden: {_js(schema['forbidden'])},",
        f"  caps: {_js(caps(env))},",
        "};",
        "",
        "// Fletcher16, arithmetic (mirrors RUN.Deathping.fletcher16): payload.sum is",
        "// fletcher16(canonical(payload)) - a cheap tamper/truncation tell the page and",
        "// the Cloud Function both recompute. The canonical string uses only ASCII-safe",
        "// tokens (kind + npc id) so Lua byte() and JS charCodeAt() always agree.",
        "export function fletcher16(s) {",
        '  s = String(s == null ? "" : s);',
        "  let a = 0, b = 0;",
        "  for (let i = 0; i < s.length; i++) { a = (a + s.charCodeAt(i)) % 255; b = (b + a) % 255; }",
        "  return b * 256 + a;",
        "}",
        "",
        "export function canonical(payload) {",
        "  const events = payload && Array.isArray(payload.events) ? payload.events : [];",
        '  const toks = events.map((e) => `${e && e.k}:${e && typeof e.npc === "number" ? e.npc : "x"}`);',
        '  return `${payload && payload.v}|${payload && payload.season}|${events.length}|${toks.join(",")}`;',
        "}",
    ]
    return "\n".join(lines) + "\n"


# ---- Firestore rules mirror (server gate) -----------------------------------

def _rule_clause(f: dict) -> str:
    """The validation clause for one envelope field (no optional-guard wrapper)."""
    k = f["key"]
    kind = f["kind"]
    if kind == "const":
        return f"d.{k} == {_js(f['value'])}"
    if kind == "string":
        c = [f"d.{k} is string", f"d.{k}.size() <= {int(f['maxSize'])}"]
        if "matches" in f:
            c.append(f"d.{k}.matches('{f['matches']}')")
        return " && ".join(c)
    if kind == "number":
        c = [f"d.{k} is number"]
        if "min" in f:
            c.append(f"d.{k} >= {_js(f['min'])}")
        if "max" in f:
            c.append(f"d.{k} <= {_js(f['max'])}")
        return " && ".join(c)
    if kind == "map":
        c = [f"d.{k} is map"]
        if "maxSize" in f:
            c.append(f"d.{k}.size() <= {int(f['maxSize'])}")
        return " && ".join(c)
    if kind == "bool":
        return f"d.{k} is bool"
    if kind == "list":
        c = [f"d.{k} is list"]
        if f.get("required"):
            c.append(f"d.{k}.size() >= 1")
        if "maxSize" in f:
            c.append(f"d.{k}.size() <= {int(f['maxSize'])}")
        if "of" in f:
            inner = "', '".join(f["of"])
            c.append(f"d.{k}.hasOnly(['{inner}'])")
        return " && ".join(c)
    raise ValueError(f"unknown kind {kind}")


def emit_rules_block(schema: dict) -> str:
    """The validRareKill function + markers, byte-for-byte deterministic,
    4-space base indent - exactly as it sits inside web/firestore.rules."""
    fields = schema["fields"]
    hasonly = "', '".join(allow_keys(fields))
    clauses = [f"d.keys().hasOnly(['{hasonly}'])"]
    for f in fields:
        clause = _rule_clause(f)
        key = f["key"]
        if f["tier"] == "identifying":
            # Identifying fields (handle/armory) may appear ONLY when the opt-in
            # flag named==true - the anonymous promise, enforced server-side.
            clauses.append(f"(!('{key}' in d) || (('named' in d) && d.named == true && {clause}))")
        elif f["kind"] == "const" or f.get("required"):
            clauses.append(clause)
        else:
            clauses.append(f"(!('{key}' in d) || ({clause}))")
    body = "\n          && ".join(clauses)
    return (
        f"    {RULES_BEGIN}\n"
        "    function validRareKill(d) {\n"
        f"      return {body};\n"
        "    }\n"
        f"    {RULES_END}"
    )


def emit_partial(schema: dict) -> str:
    return (
        f"// {GEN_NOTE}\n"
        "// Apply THIS block verbatim into the Foresight repo web/firestore.rules (next to\n"
        "// validFeedback, between the same markers). The envelope is hasOnly-shape-locked;\n"
        "// events[] internals are deep-validated by the rareKillsOnWrite function (rules\n"
        "// cannot iterate lists). Raw rareKills stay write-only, never client-readable.\n"
        + emit_rules_block(schema) + "\n"
    )


# ---- drive ------------------------------------------------------------------

def _marketing_present() -> bool:
    return (MARKETING_ROOT / "web").is_dir()


def _targets(schema: dict) -> dict[Path, str]:
    targets = {
        LUA_PATH: emit_lua(schema),
        PARTIAL_PATH: emit_partial(schema),
    }
    if _marketing_present():
        targets[JS_PATH] = emit_js(schema)
    return targets


def generate() -> list[Path]:
    schema = load_schema()
    written = []
    for path, content in _targets(schema).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        written.append(path)
    return written


def check() -> bool:
    """True iff every committed mirror equals a fresh generation, and (when the
    sibling repo is present) its firestore.rules CONTAINS the generated block."""
    schema = load_schema()
    drifted = []
    for path, content in _targets(schema).items():
        existing = path.read_text(encoding="utf-8") if path.exists() else None
        if existing != content:
            drifted.append(str(path))
    if _marketing_present() and MARKETING_RULES_PATH.exists():
        rules = MARKETING_RULES_PATH.read_text(encoding="utf-8")
        if emit_rules_block(schema) not in rules:
            drifted.append(f"{MARKETING_RULES_PATH} (validRareKill block missing or drifted)")
    if drifted:
        print("RUN CROWD SCHEMA DRIFT RED - these mirrors differ from data/rare-kills-schema.json;")
        print("run `python pipeline/gen_crowd_schema.py` (and re-apply the rules partial) then commit:")
        for d in drifted:
            print(f"  {d}")
        return False
    where = "addon + rules partial" + (" + web mirror + Foresight rules block" if _marketing_present() else "")
    print(f"run crowd schema parity green: {where} all match data/rare-kills-schema.json")
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="verify committed mirrors match the source; exit 1 on drift")
    args = parser.parse_args()
    if args.check:
        return 0 if check() else 1
    written = generate()
    for path in written:
        print(f"wrote {path} ({path.stat().st_size:,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
